'use strict';

/**
 * Regenerate lib/utils/language_names.g.dart.
 *
 *   node tool/build_language_names.js [--check]
 *
 * Language names are stored and sent as English names ("Korean",
 * "Chinese (Simplified)"), so a non-English UI showed "Speaks Korean" with
 * the language in English. This builds the DISPLAY table: language code (the
 * values of LanguageFlags._nameToCode) -> localized name, for every UI
 * locale the app ships. Same approach as tool/build_country_names.js: CLDR
 * via ICU's Intl.DisplayNames, no hand-maintained data.
 *
 * --check exits non-zero if the committed file is stale.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'utils', 'language_names.g.dart');
const FLAGS = path.join(ROOT, 'lib', 'utils', 'language_flags.dart');

// App locale key -> ICU locale (same as build_country_names.js). English is
// omitted: an English UI shows the stored English name.
const LOCALES = {
  ar: 'ar', de: 'de', es: 'es', fr: 'fr', hi: 'hi', id: 'id', it: 'it',
  ja: 'ja', ko: 'ko', pt: 'pt', ru: 'ru', tg: 'tg', th: 'th', tl: 'fil',
  tr: 'tr', vi: 'vi', zh: 'zh-Hans', zh_TW: 'zh-Hant',
};

function languageCodes() {
  const src = fs.readFileSync(FLAGS, 'utf8');
  const start = src.indexOf('_nameToCode = {');
  const end = src.indexOf('};', start);
  const block = src.slice(start, end);
  const codes = new Set();
  for (const m of block.matchAll(/'[^']+':\s*'([a-z]{2,3}(?:-[a-z0-9]+)?)'/g)) codes.add(m[1]);
  return [...codes].sort();
}

function icuTag(code) {
  // en-us -> en-US; zh-tw -> zh-Hant (the app's Traditional Chinese);
  // zh-cn -> zh-Hans; zh-hk -> yue (Cantonese is stored as zh-hk).
  if (code === 'zh-tw') return 'zh-Hant';
  if (code === 'zh-cn') return 'zh-Hans';
  if (code === 'zh-hk') return 'yue';
  const [lang, region] = code.split('-');
  return region ? `${lang}-${region.toUpperCase()}` : lang;
}

function dartString(s) {
  return JSON.stringify(s).replace(/\$/g, '\\$');
}

function build() {
  const codes = languageCodes();
  const lines = [
    '// GENERATED by tool/build_language_names.js — do not edit by hand.',
    '// Source: CLDR language display names via ICU Intl.DisplayNames',
    `// (Node ${process.version}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr}).`,
    '',
    '/// App locale key (as in lib/l10n/app_<key>.arb) -> language code (as in',
    '/// LanguageFlags) -> localized language name. English is not listed: an',
    '/// English UI shows the stored English name. A code with no CLDR name is',
    '/// left out and falls back to the stored name.',
    'const Map<String, Map<String, String>> kLanguageNamesByLocale = {',
  ];
  for (const [key, icu] of Object.entries(LOCALES)) {
    const dn = new Intl.DisplayNames([icu], { type: 'language', fallback: 'none' });
    lines.push(`  ${dartString(key)}: {`);
    for (const code of codes) {
      let name;
      try { name = dn.of(icuTag(code)); } catch { name = undefined; }
      if (name) lines.push(`    ${dartString(code)}: ${dartString(name)},`);
    }
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

const out = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('lib/utils/language_names.g.dart is stale; run node tool/build_language_names.js');
    process.exit(1);
  }
  console.log('language_names.g.dart is up to date');
} else {
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
