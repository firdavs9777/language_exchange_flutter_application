'use strict';

/**
 * Regenerate lib/utils/country_names.g.dart.
 *
 *   node tool/build_country_names.js [--check]
 *
 * Country names shown in the app (community filter list, City tab, location
 * lines) are stored and sent as English names / ISO codes. This builds the
 * DISPLAY table only: ISO 3166-1 alpha-2 code -> name, for every UI locale
 * the app ships (lib/l10n/app_*.arb).
 *
 * Data source: CLDR, via ICU's Intl.DisplayNames as bundled with Node — the
 * same approach as the backend's scripts/buildCountryNames.js. No dependency,
 * no hand-maintained data. The header of the generated file records the
 * Node/ICU/CLDR versions it was built with.
 *
 * --check regenerates in memory and exits non-zero if the committed file is
 * stale.
 */

const fs = require('node:fs');
const path = require('node:path');

const OUT = path.join(__dirname, '..', 'lib', 'utils', 'country_names.g.dart');

// App locale key -> ICU locale. Keys match lib/l10n/app_<key>.arb.
// English is omitted on purpose: in English the stored name is shown as is.
const LOCALES = {
  ar: 'ar',
  de: 'de',
  es: 'es',
  fr: 'fr',
  hi: 'hi',
  id: 'id',
  it: 'it',
  ja: 'ja',
  ko: 'ko',
  pt: 'pt',
  ru: 'ru',
  tg: 'tg',
  th: 'th',
  tl: 'fil',
  tr: 'tr',
  vi: 'vi',
  zh: 'zh-Hans',
  zh_TW: 'zh-Hant',
};

// Region codes that are not places a user lives in (groupings, pseudo and
// uninhabited territories).
const SKIP = new Set([
  'AC', 'AQ', 'BV', 'CP', 'CQ', 'DG', 'EA', 'EU', 'EZ', 'HM', 'IC', 'QO',
  'TA', 'TF', 'UM', 'UN', 'XA', 'XB', 'ZZ',
]);

function regionCodes() {
  const en = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'none' });
  const codes = [];
  for (let a = 65; a <= 90; a++) {
    for (let b = 65; b <= 90; b++) {
      const code = String.fromCharCode(a, b);
      if (SKIP.has(code)) continue;
      if (!en.of(code)) continue;
      // Deprecated codes (DD, SU, FX...) canonicalise to their replacement
      // and would otherwise duplicate the current country's name.
      let canonical;
      try {
        canonical = new Intl.Locale(`und-${code}`).region;
      } catch {
        continue;
      }
      if (canonical !== code) continue;
      codes.push(code);
    }
  }
  return codes;
}

function dartString(s) {
  return JSON.stringify(s).replace(/\$/g, '\\$');
}

function build() {
  const codes = regionCodes();
  const lines = [
    '// GENERATED by tool/build_country_names.js — do not edit by hand.',
    '// Source: CLDR region display names via ICU Intl.DisplayNames',
    `// (Node ${process.version}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr}).`,
    '',
    '/// App locale key (as in lib/l10n/app_<key>.arb) -> ISO 3166-1 alpha-2',
    '/// code -> localized country name. English is not listed: an English UI',
    '/// shows the stored English name.',
    'const Map<String, Map<String, String>> kCountryNamesByLocale = {',
  ];
  for (const [key, icu] of Object.entries(LOCALES)) {
    const dn = new Intl.DisplayNames([icu], { type: 'region', fallback: 'none' });
    lines.push(`  ${dartString(key)}: {`);
    for (const code of codes) {
      const name = dn.of(code);
      if (name) lines.push(`    ${dartString(code)}: ${dartString(name)},`);
    }
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

const out = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('lib/utils/country_names.g.dart is stale; run node tool/build_country_names.js');
    process.exit(1);
  }
  console.log('country_names.g.dart is up to date');
} else {
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
